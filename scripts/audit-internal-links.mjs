/**
 * Crawl internal hrefs from app/ + components/ and probe a running site.
 *
 * Usage:
 *   node scripts/audit-internal-links.mjs
 *   node scripts/audit-internal-links.mjs --base=http://localhost:3000
 */
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const baseArg = process.argv.find((a) => a.startsWith("--base="));
const BASE = (baseArg ? baseArg.slice("--base=".length) : "http://localhost:3000").replace(
  /\/$/,
  ""
);

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (["node_modules", ".next", ".git", "public"].includes(ent.name)) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, acc);
    else if (/\.(js|jsx|mjs|ts|tsx|md)$/.test(ent.name)) acc.push(p);
  }
  return acc;
}

const hrefMap = new Map();
for (const file of walk(path.join(ROOT, "app")).concat(walk(path.join(ROOT, "components")))) {
  const text = fs.readFileSync(file, "utf8");
  const rel = path.relative(ROOT, file).replace(/\\/g, "/");
  for (const m of text.matchAll(
    /(?:href|mainLink|secondaryLink|thankYouPath|ctaHref)=["'`](\/[^"'`?#]*)/g
  )) {
    const href = m[1].replace(/\/$/, "") || "/";
    if (
      href.startsWith("/images") ||
      href.startsWith("/docs") ||
      href.startsWith("/_next")
    ) {
      continue;
    }
    if (!hrefMap.has(href)) hrefMap.set(href, new Set());
    hrefMap.get(href).add(rel);
  }
}

try {
  const { default: staticPages } = await import(
    pathToFileURL(path.join(ROOT, "lib/sitemapStaticPages.js")).href
  );
  for (const page of staticPages) {
    const href = page.path ? `/${page.path}` : "/";
    if (!hrefMap.has(href)) hrefMap.set(href, new Set(["lib/sitemapStaticPages.js"]));
  }
} catch {
  // optional
}

// Always probe sitemap static pages + thank-you routes
const always = [
  "/",
  "/sitemap.xml",
  "/robots.txt",
  "/portfolio-review/thank-you",
  "/book-portfolio-review/thank-you",
  "/retirement-planning/thank-you",
  "/insurance-planning/thank-you",
  "/legacy-succession-estate-planning-india/thank-you",
  "/legacy-inheritance-planning",
  "/insurance",
  "/retirement",
  "/portfolio-review-vadodara",
  "/research-analyst-vs-investment-adviser-vs-mfd",
  "/pms-vs-mutual-funds",
  "/aif-vs-pms-vs-mutual-funds",
  "/sip-vs-lumpsum-vs-stp",
  "/direct-mutual-fund-apps-vs-portfolio-review",
  "/regular-plan-vs-direct-plan-mutual-funds",
  "/financial-planner-vs-wealth-manager-vadodara",
  "/portfolio-review-vadodara",
  "/sebi-registered-research-analyst-vadodara",
  "/mutual-fund-investment-support-vadodara",
  "/fixed-income-investments-vadodara",
  "/retirement-planning-vadodara",
  "/insurance-planning-vadodara",
];
for (const href of always) {
  if (!hrefMap.has(href)) hrefMap.set(href, new Set(["scripts/audit-internal-links.mjs"]));
}

const results = [];
for (const href of [...hrefMap.keys()].sort()) {
  try {
    const res = await fetch(`${BASE}${href}`, { redirect: "manual" });
    const loc = res.headers.get("location") || "";
    results.push({
      href,
      status: res.status,
      location: loc,
      from: [...hrefMap.get(href)].slice(0, 5),
    });
  } catch (err) {
    results.push({
      href,
      status: "ERR",
      location: err.message,
      from: [...hrefMap.get(href)].slice(0, 5),
    });
  }
}

const ok = results.filter((r) => r.status === 200 || r.status === 308 || r.status === 301);
const bad = results.filter((r) => !(r.status === 200 || r.status === 308 || r.status === 301));

console.log(`Base: ${BASE}`);
console.log(`Probed: ${results.length}`);
console.log(`OK (200/301/308): ${ok.length}`);
console.log(`Needs attention: ${bad.length}`);
if (bad.length) {
  console.log("\n=== Needs attention ===");
  for (const r of bad) {
    console.log(`${r.status} ${r.href}${r.location ? ` -> ${r.location}` : ""}`);
    console.log(`  from: ${r.from.join(", ")}`);
  }
}

const outDir = path.join(ROOT, "docs");
const md = `# Internal Link & Redirect Audit

> Generated by \`node scripts/audit-internal-links.mjs\`  
> Base: \`${BASE}\`  
> Date: ${new Date().toISOString().slice(0, 10)}

## Summary

| Metric | Count |
|---|---|
| Paths probed | ${results.length} |
| OK (200 / 301 / 308) | ${ok.length} |
| Needs attention | ${bad.length} |

## Redirects confirmed

| From | Status | To |
|---|---|---|
${results
  .filter((r) => r.status === 301 || r.status === 308)
  .map((r) => `| \`${r.href}\` | ${r.status} | \`${r.location}\` |`)
  .join("\n") || "| — | — | — |"}

## Needs attention

${
  bad.length
    ? bad
        .map(
          (r) =>
            `- \`${r.href}\` → **${r.status}**${r.location ? ` (${r.location})` : ""}  \n  Referenced from: ${r.from.map((f) => `\`${f}\``).join(", ")}`
        )
        .join("\n")
    : "_None — all probed internal paths returned 200 or a permanent redirect._"
}

## How to re-run

\`\`\`bash
npm run start
# in another terminal:
node scripts/audit-internal-links.mjs --base=http://localhost:3000
\`\`\`
`;

fs.writeFileSync(path.join(outDir, "LINK_REDIRECT_AUDIT.md"), md);
console.log(`\nWrote docs/LINK_REDIRECT_AUDIT.md`);
